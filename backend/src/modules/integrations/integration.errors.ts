export type IntegrationErrorCode =
  (typeof INTEGRATION_ERRORS)[keyof typeof INTEGRATION_ERRORS];

export class IntegrationError extends AppError {
  public constructor(message: string, code: IntegrationErrorCode, statusCode = 400) {
    super(message, code, statusCode);
    this.name = "IntegrationError";
  }
}

export function safeIntegrationError(error: unknown): {
  code: string;
  message: string;
} {
  if (error instanceof AppError) {
    return {
      code: error.code,
      message: truncate(error.message)
    };
  }

  return {
    code: INTEGRATION_ERRORS.SYNC_PROCESSING_FAILED,
    message: "Synchronization item could not be processed safely."
  };
}

function truncate(value: string): string {
  const normalized = value.replace(/\s+/g, " ").trim();

  return normalized.length > 500 ? `${normalized.slice(0, 497)}...` : normalized;
}
